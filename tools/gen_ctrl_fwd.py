# gen_ctrl_fwd.py 01/10/2026. Writes src/GekkoHook/GekkoCtrlFwd.asm and GekkoCtrlSlots.h from research/ctrl_slot_verify.tsv: one forwarder per Survive controller slot that has exactly one identical TPP slot
# (tools/verify_ctrl_slots.py) and is instance-indexed, plus the hand-verified overrides below. Survive slot N -> fwd_cN.
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OVERRIDE = {   # slot -> (TPP offset, why)
    62: (0x1d0, "set motion: twin overloads 57/58 match; the Survive callee 0x140c39d70 matches TPP slot 58's target 0x140b6e920 (2a0-byte frame), not slot 57's"),
    42: (0x130, "twin 38/40 identical"),
    122: (0x380, "unit +0x60 -> +0x10 object: Survive 0x140bc20c0 = TPP slot 112 0x140af1130, identical code (twin 113); MEASURED 01/10 the object holds the unit position at +0x20 and rotation at +0x60 like Survive's"),
    123: (0x380, "same function as slot 122"),
}
rows = {}
for r in csv.DictReader(open(ROOT / "research" / "ctrl_slot_verify.tsv", encoding="utf-8"), delimiter=chr(9)):
    if r["verdict"].strip() == "unique" and r["id_indexed"].strip() == "yes":
        t = r["tpp_matches"].strip()
        rows[int(r["survive_slot"])] = (int(t[t.index("(") + 1:t.index(")")], 16), "slot %s unique" % t)
rows.update(OVERRIDE)
asm = ["; GekkoCtrlFwd.asm 01/10/2026 (generated by tools/gen_ctrl_fwd.py, do not edit). Forwarders that let lifted Survive code call TPP's real AnimationControllerImpl: the stub swaps `this` for the real",
       "; controller and the instance id for unit 0 and tail-jumps, so r8/r9, xmm and stack arguments and the return value pass through. One per Survive slot with exactly one identical TPP slot.",
       ".data", "public g_fwdCtrl", "g_fwdCtrl dq 0", "", ".code", "FWD macro name, off", "public name", "name proc", "    mov rcx, g_fwdCtrl", "    xor edx, edx",
       "    mov rax, qword ptr [rcx]", "    jmp qword ptr [rax + off]", "name endp", "endm", ""]
hdr = ["// GekkoCtrlSlots.h 01/10/2026 (generated by tools/gen_ctrl_fwd.py, do not edit). Survive controller slot -> forwarder to the identical TPP slot.", "#pragma once", ""]
decl, tab = [], []
for s in sorted(rows):
    off, why = rows[s]
    asm.append("FWD fwd_c%d, %04xh   ; Survive +0x%x -> TPP +0x%x (%s)" % (s, off, s * 8, off, why))
    decl.append("fwd_c%d" % s)
    tab.append("{ %d, fwd_c%d }" % (s, s))
asm.append("end")
hdr.append('extern "C" void ' + "(), ".join(decl) + "();")
hdr.append("struct CtrlFwd { int slot; void (*fn)(); };")
hdr.append("static const CtrlFwd kCtrlFwd[] = { " + ", ".join(tab) + " };")
(ROOT / "src" / "GekkoHook" / "GekkoCtrlFwd.asm").write_text(chr(10).join(asm) + chr(10), encoding="utf-8")
(ROOT / "src" / "GekkoHook" / "GekkoCtrlSlots.h").write_text(chr(10).join(hdr) + chr(10), encoding="utf-8")
print(len(rows), "forwarders")
